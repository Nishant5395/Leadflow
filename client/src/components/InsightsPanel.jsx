export default function InsightsPanel({ status, insight, error, onUse, onDismiss, canSuggest }) {
  if (status === 'idle') return null;

  return (
    <section className="insights" aria-label="Lead summary" aria-live="polite" aria-busy={status === 'loading'}>
      <div className="insights-head">
        <strong>
          <span aria-hidden="true">✨</span> Summary &amp; next step
        </strong>
        {insight && (
          <span className="tag" title={insight.source === 'ai' ? 'Written by AI from the discussion notes' : 'Generated by simple rules from the status and notes'}>
            {insight.source === 'ai' ? 'AI' : 'Rule-based'}
          </span>
        )}
        <button type="button" className="icon-btn small" aria-label="Dismiss summary" onClick={onDismiss}>
          ×
        </button>
      </div>

      {status === 'loading' && (
        <div className="stack tight">
          <div className="skeleton" style={{ height: 14, width: '92%' }} />
          <div className="skeleton" style={{ height: 14, width: '70%' }} />
        </div>
      )}

      {status === 'error' && <div className="banner-error">{error}</div>}

      {status === 'ready' && insight && (
        <>
          <p className="insights-summary">{insight.summary}</p>
          <p className="insights-next">
            <span className="label">Suggested next step:</span> {insight.nextStep}
          </p>
          {canSuggest && (
            <button type="button" className="pill" onClick={() => onUse(insight.followUpDays)}>
              Use suggested follow-up ({insight.followUpDays === 0 ? 'today' : `in ${insight.followUpDays} day${insight.followUpDays === 1 ? '' : 's'}`})
            </button>
          )}
        </>
      )}
    </section>
  );
}
